-- FIDEN · esquema inicial
-- Productos, stock, pedidos, clientes y administradores.

create extension if not exists pgcrypto;

-- ───────────── Categorías ─────────────
create table public.categories (
  slug        text primary key,
  name        text not null,
  subtitle    text not null default '',
  image       text not null default '',
  position    int  not null default 0
);

-- ───────────── Productos ─────────────
create table public.products (
  id          bigint generated by default as identity primary key,
  slug        text unique not null,
  category    text not null references public.categories(slug) on update cascade,
  name        text not null,
  image       text not null default '',
  price       numeric(10,2) not null check (price >= 0),
  compare_at  numeric(10,2) check (compare_at is null or compare_at >= 0),
  tag         text check (tag in ('Nuevo','Oferta')),
  popularity  int  not null default 0,
  stock       int  not null default 0 check (stock >= 0),
  featured    boolean not null default false,
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index products_category_idx on public.products(category);

-- ───────────── Administradores ─────────────
create table public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ───────────── Clientes ─────────────
create table public.customers (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid references auth.users(id) on delete set null,
  name       text not null,
  phone      text unique not null,
  email      text,
  city       text,
  address    text,
  created_at timestamptz not null default now()
);

-- ───────────── Pedidos ─────────────
create table public.orders (
  id           uuid primary key default gen_random_uuid(),
  number       bigint generated always as identity (start with 1001) unique,
  customer_id  uuid references public.customers(id) on delete set null,
  user_id      uuid references auth.users(id) on delete set null,
  name         text not null,
  phone        text not null,
  city         text not null,
  address      text not null,
  payment      text not null check (payment in ('efectivo','transferencia','deuna','tarjeta')),
  status       text not null default 'pendiente'
               check (status in ('pendiente','pendiente_pago','pagado','enviado','entregado','cancelado')),
  subtotal     numeric(10,2) not null,
  shipping     numeric(10,2) not null,
  total        numeric(10,2) not null,
  payment_ref  text,          -- id de transacción de Payphone
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index orders_created_idx on public.orders(created_at desc);

create table public.order_items (
  id          bigint generated always as identity primary key,
  order_id    uuid not null references public.orders(id) on delete cascade,
  product_id  bigint references public.products(id) on delete set null,
  name        text not null,
  price       numeric(10,2) not null,
  qty         int not null check (qty > 0)
);
create index order_items_order_idx on public.order_items(order_id);

-- ───────────── Newsletter ─────────────
create table public.subscribers (
  email      text primary key,
  created_at timestamptz not null default now()
);

-- ───────────── updated_at ─────────────
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger products_touch before update on public.products for each row execute function public.touch_updated_at();
create trigger orders_touch   before update on public.orders   for each row execute function public.touch_updated_at();

-- ───────────── Crear pedido (atómico, valida stock) ─────────────
-- p_items: [{"id": 1, "qty": 2}, ...]
create or replace function public.create_order(
  p_items jsonb, p_name text, p_phone text, p_city text, p_address text,
  p_payment text, p_user_id uuid default null, p_email text default null
) returns public.orders
language plpgsql security definer set search_path = public as $$
declare
  free_ship constant numeric := 50;
  ship_cost constant numeric := 3.50;
  it jsonb; prod public.products; q int;
  v_sub numeric := 0; v_ship numeric;
  v_customer uuid; v_order public.orders;
begin
  if jsonb_array_length(coalesce(p_items, '[]'::jsonb)) = 0 then
    raise exception 'EMPTY_CART';
  end if;

  -- Bloquea y valida cada producto
  for it in select * from jsonb_array_elements(p_items) loop
    q := (it->>'qty')::int;
    select * into prod from products where id = (it->>'id')::bigint and active for update;
    if not found then raise exception 'NOT_FOUND:%', it->>'id'; end if;
    if q is null or q <= 0 then raise exception 'BAD_QTY'; end if;
    if prod.stock < q then raise exception 'NO_STOCK:%', prod.name; end if;
    v_sub := v_sub + prod.price * q;
  end loop;

  v_ship := case when v_sub >= free_ship then 0 else ship_cost end;

  insert into customers (user_id, name, phone, email, city, address)
  values (p_user_id, p_name, p_phone, p_email, p_city, p_address)
  on conflict (phone) do update set
    name = excluded.name, city = excluded.city, address = excluded.address,
    user_id = coalesce(excluded.user_id, customers.user_id),
    email = coalesce(excluded.email, customers.email)
  returning id into v_customer;

  insert into orders (customer_id, user_id, name, phone, city, address, payment, status, subtotal, shipping, total)
  values (v_customer, p_user_id, p_name, p_phone, p_city, p_address, p_payment,
          case when p_payment = 'tarjeta' then 'pendiente_pago' else 'pendiente' end,
          v_sub, v_ship, v_sub + v_ship)
  returning * into v_order;

  for it in select * from jsonb_array_elements(p_items) loop
    q := (it->>'qty')::int;
    update products set stock = stock - q where id = (it->>'id')::bigint returning * into prod;
    insert into order_items (order_id, product_id, name, price, qty)
    values (v_order.id, prod.id, prod.name, prod.price, q);
  end loop;

  return v_order;
end $$;

-- Cancela un pedido y devuelve el stock (solo si no se ha enviado)
create or replace function public.cancel_order(p_order uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform 1 from orders where id = p_order and status in ('pendiente','pendiente_pago','pagado') for update;
  if not found then return; end if;
  update products p set stock = p.stock + i.qty
    from order_items i where i.order_id = p_order and i.product_id = p.id;
  update orders set status = 'cancelado' where id = p_order;
end $$;

-- Las funciones de pedidos solo se llaman desde el servidor (service role)
revoke all on function public.create_order(jsonb,text,text,text,text,text,uuid,text) from public, anon, authenticated;
revoke all on function public.cancel_order(uuid) from public, anon, authenticated;

-- ───────────── Seguridad (RLS) ─────────────
alter table public.categories  enable row level security;
alter table public.products    enable row level security;
alter table public.admins      enable row level security;
alter table public.customers   enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;
alter table public.subscribers enable row level security;

-- Catálogo público
create policy "catálogo visible" on public.categories for select using (true);
create policy "productos activos visibles" on public.products for select using (active or public.is_admin());

-- Admin gestiona catálogo
create policy "admin categorías" on public.categories for all using (public.is_admin()) with check (public.is_admin());
create policy "admin productos"  on public.products   for all using (public.is_admin()) with check (public.is_admin());

-- Admin ve a los administradores
create policy "admin ve admins" on public.admins for select using (public.is_admin());

-- Clientes: el admin ve todo; cada cliente ve lo suyo
create policy "admin clientes" on public.customers for all using (public.is_admin()) with check (public.is_admin());
create policy "cliente propio" on public.customers for select using (user_id = auth.uid());

create policy "admin pedidos" on public.orders for all using (public.is_admin()) with check (public.is_admin());
create policy "pedidos propios" on public.orders for select using (user_id = auth.uid());

create policy "admin items" on public.order_items for all using (public.is_admin()) with check (public.is_admin());
create policy "items propios" on public.order_items for select
  using (exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));

create policy "admin suscriptores" on public.subscribers for select using (public.is_admin());

